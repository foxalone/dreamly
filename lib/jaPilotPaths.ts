export type JaAdditionalDreamSlug = (typeof JA_ADDITIONAL_DREAM_BATCHES)[number]["slugs"][number];
const JA_ADDITIONAL_DREAM_SLUGS = JA_ADDITIONAL_DREAM_BATCHES.flatMap<JaAdditionalDreamSlug>(({ slugs }) => slugs);

export const JA_WEB_DREAM_SLUGS = [...JA_PILOT_SLUGS, ...JA_ADDITIONAL_DREAM_SLUGS] as const;
export type JaWebDreamSlug = (typeof JA_WEB_DREAM_SLUGS)[number];

const JA_PILOT_UPDATED_AT = "2026-11-16";
const datesBySlug = new Map<string, string>([
  ...JA_PILOT_SLUGS.map((slug): [string, string] => [slug, JA_PILOT_UPDATED_AT]),
  ...JA_ADDITIONAL_DREAM_BATCHES.flatMap(({ slugs, updatedAt }) =>
    slugs.map((slug): [string, string] => [slug, updatedAt]),
  ),
]);

export const JAPANESE_DICTIONARY_UPDATED_AT = JA_ADDITIONAL_DREAM_BATCHES.reduce<string>(
  (latest, { updatedAt }) => updatedAt > latest ? updatedAt : latest,
  JA_PILOT_UPDATED_AT,
);

export function getJapaneseDreamUpdatedAt(slug: string): string | undefined {
  return datesBySlug.get(slug);
}

const japanesePaths = new Map<string, string>([
  ["/", "/ja"],
  ["/dreams", "/ja/dreams"],
  ...JA_WEB_DREAM_SLUGS.map((slug): [string, string] => [`/dreams/${slug}`, `/ja/dreams/${slug}`]),
]);

const pilotPaths = new Set(japanesePaths.values());

export function jaPilotAlternate(path: string): string | undefined {
  return japanesePaths.get(path);
}

export function isJaPilotPath(path: string): boolean {
  return pilotPaths.has(path);
}

export function isJaDreamFormPath(path: string): boolean {
  return path.startsWith("/ja/dreams/") && isJaPilotPath(path);
}
